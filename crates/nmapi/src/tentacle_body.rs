fn bad(m: impl Into<String>) -> Fault {
    Fault::new("nmapi.tentacle_body", FaultKind::Execution, m)
}

/// The file stem of tentacle `n` (1-based, lens order).
#[must_use]
pub fn stem(n: usize) -> String {
    format!("tentacle-t{n}")
}

/// The note written into every generated assembly.
pub const NOTE: &str = "A tentacle's own neural body (2026-11-10; architecture by Luis Jake Gabriel III): generated by `nano-lab run tentacle assemblies` from designs/tentacle-core.json and this tentacle's drone set in designs/drones.json (nmengn::tentacle::assembly); sensory segments t<n>.S<l> through the tentacle's last drone layer and its drone tip t<n>.tip.L<l>.g<g> owning the drone heads' scoring; no layer above the last drone layer, no final norm, no output head. Cluster references name tensor and region; the shared population is supplied when it binds. Do not edit by hand.";

/// The generated assemblies, in lens order: (lens, tentacle prefix, assembly).
/// # Errors
/// The specification, the drone sets or the reference assembly cannot be read.
pub fn generate(home: &Path) -> Result<Vec<(String, String, nmengn::Assembly)>, Fault> {
    let spec = crate::tentacle_core::load_spec(home).map_err(bad)?;
    let sets = nmengn::kvstore::drone_set(home, &spec.population)?;
    let reference = nmengn::Assembly::load(&home.join("designs/assemblies"), "qwen3-reference")?;
    let (g, _) = crate::tentacle_core::population_groups(home, &spec.population).map_err(bad)?;
    let mut out = Vec::new();
    for (i, lens) in nmsubs::lens::NAMES.iter().enumerate() {
        let t = format!("t{}", i + 1);
        let mut a = tentacle::assembly(&reference, &t, sets.for_tentacle(lens), g.heads, g.kv_heads)?;
        a.name = format!("{}-{lens}", stem(i + 1));
        out.push(((*lens).to_owned(), t, a));
    }
    Ok(out)
}

/// Write the generated assemblies; returns (file, components) per tentacle.
/// # Errors
/// As `generate`, or a write fault.
pub fn write(home: &Path) -> Result<Vec<(String, usize)>, Fault> {
    let mut out = Vec::new();
    for (i, (_, _, a)) in generate(home)?.into_iter().enumerate() {
        let p = home.join("designs/assemblies").join(format!("{}.json", stem(i + 1)));
        let text = nmjson::pretty::pretty(&a.to_value(NOTE));
        std::fs::write(&p, format!("{text}\n")).map_err(|e| bad(format!("{}: {e}", p.display())))?;
        out.push((p.display().to_string(), a.nodes.len()));
    }
    Ok(out)
}

/// One tentacle's bound body.
pub struct Body {
    pub lens: String,
    pub prefix: String,
    pub model: Arc<Model>,
    /// Its drone tip's scoring components (the run targets of a read) and the heads they cover.
    pub stop: Vec<(String, String)>,
    pub heads: Vec<(usize, usize)>,
    /// Whether the assembly file on disk equals a fresh generation (a stale file is not bound).
    pub file_current: bool,
}
impl std::fmt::Debug for Body {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("Body").field("lens", &self.lens).field("prefix", &self.prefix).finish_non_exhaustive()
    }
}
impl Body {
    /// True when this body's tip covers every head of `heads`.
    #[must_use]
    pub fn covers(&self, heads: &[(usize, usize)]) -> bool {
        let mine: BTreeSet<&(usize, usize)> = self.heads.iter().collect();
        heads.iter().all(|h| mine.contains(h))
    }
    /// A drone read of `w` through this body (`tentacle_pass::drone_read_logits`, recorded at the tip).
    /// # Errors
    /// Engine faults.
    pub fn read(&self, dev: Device, w: &Arc<Window>, heads: &[(usize, usize)], text: &str) -> Result<(Vec<f32>, Vec<f32>), Fault> {
        tentacle_pass::drone_read_logits_with(&self.model, dev, w, &self.stop, heads, text, Some(TIP))
    }
    /// One line of facts: components, clusters, host and device bytes, sharing.
    #[must_use]
    pub fn facts(&self, reference: &Model) -> String {
        let (n, host, dev) = self.model.holdings();
        let comps = self.model.components();
        let tip = comps.iter().filter(|c| c.0.contains(TIP)).count();
        let ref_ids: BTreeSet<String> = reference.components().into_iter().flat_map(|c| c.2).collect();
        let mine: BTreeSet<String> = comps.iter().flat_map(|c| c.2.iter().cloned()).collect();
        let shared = mine.intersection(&ref_ids).count();
        let layers = comps
            .iter()
            .filter_map(|c| {
                c.0.split(&format!("{}.S", self.prefix)).nth(1).and_then(|r| r.split('.').next()).and_then(|l| l.parse::<usize>().ok())
            })
            .max()
            .unwrap_or(0);
        format!(
            "{} ({}): {} components ({} in the drone tip), sensory segments through layer {layers}, {n} parameter clusters held ({shared} also held by the reference path, every one provisioned by reference from the shared population), host {:.1} MB in shared views (zero copy), device {:.1} MB of weight copies resident now (keyed by cluster, shared with any model of the population that uses the same cluster); tip heads {}; assembly file current: {}",
            self.prefix,
            self.lens,
            comps.len(),
            tip,
            host as f64 / 1e6,
            dev as f64 / 1e6,
            self.heads.iter().map(|(l, h)| format!("L{l}.h{h}")).collect::<Vec<_>>().join(" "),
            self.file_current
        )
    }
}

static BODIES: OnceLock<Arc<Vec<Arc<Body>>>> = OnceLock::new();

/// The bodies of the eight tentacles, bound once per process over the base population. A body
/// whose assembly file differs from a fresh generation is not bound (its tentacle reads through
/// the reference path) until `run tentacle assemblies` writes it again.
/// # Errors
/// The base model or a body cannot be bound.
pub fn bodies(home: &Path) -> Result<Arc<Vec<Arc<Body>>>, Fault> {
    if let Some(b) = BODIES.get() {
        return Ok(Arc::clone(b));
    }
    let base = crate::neural::model(home)?;
    let mut out = Vec::new();
    for (i, (lens, prefix, fresh)) in generate(home)?.into_iter().enumerate() {
        let on_disk = nmengn::Assembly::load(&home.join("designs/assemblies"), &stem(i + 1)).ok();
        let current = on_disk.as_ref().is_some_and(|a| a.to_value(NOTE).encode().ok() == fresh.to_value(NOTE).encode().ok());
        if !current {
            continue;
        }
        let stop = tentacle::tip_targets(&fresh);
        let sets = tentacle_pass::drones(home);
        let heads = sets.for_tentacle(&lens).to_vec();
        let mut fresh = fresh;
        crate::neural::served_width(&mut fresh, &base.pop.card.id, false);
        let model = Arc::new(Model::bind(&base.pop, fresh)?);
        out.push(Arc::new(Body { lens, prefix, model, stop, heads, file_current: current }));
    }
    Ok(Arc::clone(BODIES.get_or_init(|| Arc::new(out))))
}

/// `anatomy tentacles` from the bound bodies: per tentacle its modules (sensory segments by layer,
/// the drone tip by layer and group) with the clusters each holds, and its facts.
/// # Errors
/// The bodies cannot be bound.
pub fn anatomy_table(home: &Path) -> Result<String, Fault> {
    use std::fmt::Write as _;
    let base = crate::neural::model(home)?;
    let bs = bodies(home)?;
    let mut out = String::new();
    let _ = writeln!(
        out,
        "Tentacle bodies as bound (2026-11-10): {} of {} tentacles bound to their own generated assembly over the shared population {}.",
        bs.len(),
        nmsubs::lens::NAMES.len(),
        base.pop.card.id
    );
    for b in bs.iter() {
        let _ = writeln!(out, "\n{}", b.facts(&base));
        let _ = writeln!(out, "| module | components | clusters held |");
        let _ = writeln!(out, "|---|---|---|");
        let mut modules: std::collections::BTreeMap<String, (usize, usize)> = std::collections::BTreeMap::new();
        for (id, _, cl) in b.model.components() {
            let inst = id.strip_prefix("nmengn.components#").unwrap_or(&id);
            let module = match inst.split('.').collect::<Vec<_>>().as_slice() {
                [_, "tip", l, g, ..] => format!("drone tip {l} {g}"),
                [_, s, ..] if s.starts_with('S') => format!("sensory segment {}", s.trim_start_matches('S')),
                [_, "embed"] => "embedding".to_owned(),
                _ => inst.to_owned(),
            };
            let e = modules.entry(module).or_default();
            e.0 += 1;
            e.1 += cl.len();
        }
        for (m, (c, k)) in modules {
            let _ = writeln!(out, "| {m} | {c} | {k} |");
        }
    }
    Ok(out)
}

/// Section check (2026-11-10): (a) every generated assembly validates and the files on disk equal a
/// fresh generation; (b) the bodies bind over the base population (one population object, pointer
/// identity); (c) on a three-file tree and a full window of the mini's own tree, each tentacle's
/// drone readings through its body equal the reference path's on the same window bit for bit
/// (mass and raw-score rows), on the device the base model uses; (d) per body its facts. Values:
/// `tests/section-checks/nmapi-tentacle-body/report.txt`.
/// # Errors
/// One fault line.
pub fn check() -> Result<(), String> {
    use std::fmt::Write as _;
    let mut rep = String::from("nmapi.tentacle_body (tentacle bodies: own assemblies, bound by reference, read at the tip)\n");
    let r = body_check(&mut rep);
    let _ = writeln!(rep, "result: {}", r.as_ref().map_or_else(|e| format!("FAIL {e}"), |()| "ok".to_owned()));
    let dir = nmtype::check_dir("nmapi-tentacle-body").map_err(|e| e.to_string())?;
    std::fs::write(dir.join("report.txt"), rep).map_err(|e| e.to_string())?;
    r
}

fn body_check(rep: &mut String) -> Result<(), String> {
    use std::fmt::Write as _;
    let home = nmtype::nano_root();
    let base = crate::neural::model(&home).map_err(|e| e.to_string())?;
    let bs = bodies(&home).map_err(|e| e.to_string())?;
    let _ = writeln!(
        rep,
        "(a, b) {} of {} bodies bound (a body is bound only when its file equals a fresh generation)",
        bs.len(),
        nmsubs::lens::NAMES.len()
    );
    if bs.len() != nmsubs::lens::NAMES.len() {
        return Err("an assembly file is missing or stale: run `nano-lab run tentacle assemblies`".into());
    }
    let mut one_pop = true;
    for b in bs.iter() {
        one_pop &= Arc::ptr_eq(&b.model.pop, &base.pop);
        let _ = writeln!(rep, "(d) {}", b.facts(&base));
    }
    if !one_pop {
        return Err("a body bound over another population object".into());
    }
    // (c) Equality on a small tree's windows.
    let dev = if base.pop.gpu.is_some() { Device::Gpu } else { Device::Cpu };
    let embed: nmsubs::Embed = Arc::new(|_: &str| vec![0.0; 4]);
    let files = [
        (
            "a/ring.rs",
            "pub struct Ring { items: Vec<u32>, head: usize }\nimpl Ring {\n    pub fn push(&mut self, x: u32) { let n = self.items.len(); self.items[self.head % n] = x; self.head += 1; }\n}\n",
        ),
        (
            "a/clock.rs",
            "pub fn tick(now: u64, step: u64) -> u64 { now.wrapping_add(step) }\npub fn late(now: u64, due: u64) -> bool { now > due }\n",
        ),
        (
            "a/limit.rs",
            "pub struct Limit { bytes: usize }\nimpl Limit {\n    pub fn room(&self, used: usize) -> usize { self.bytes.saturating_sub(used) }\n}\n",
        ),
    ];
    let sub = nmsubs::from_files(&files, embed);
    let settings = tentacle_pass::Settings { core: true, ..tentacle_pass::Settings::served() };
    let pass = tentacle_pass::TentaclePass::new(&home, settings);
    let (scan, _) = pass.scan(&sub, "where is the free room of a limit computed?", &settings).map_err(|e| e.to_string())?;
    let sets = tentacle_pass::drones(&home);
    let stop = nmengn::kvstore::score_targets(&base, sets.last_layer()).map_err(|e| e.to_string())?;
    let bits = |v: &[f32]| v.iter().map(|x| x.to_bits()).collect::<Vec<u32>>();
    let mut values = 0_usize;
    for w in &scan.windows {
        let Some(win) = w.window.as_ref() else { continue };
        let lens = nmsubs::lens::NAMES.get(w.tentacle).copied().unwrap_or("meaning");
        let b = bs.iter().find(|b| b.lens == lens).ok_or("no body")?;
        let heads = sets.for_tentacle(lens);
        for text in ["\nQuestion: where is the free room of a limit computed?", "\nQuestion: N/A"] {
            let (rm, rc) = tentacle_pass::drone_read_logits(&base, dev, win, &stop, heads, text).map_err(|e| e.to_string())?;
            let (bm, bc) = b.read(dev, win, heads, text).map_err(|e| e.to_string())?;
            if bits(&rm) != bits(&bm) || bits(&rc) != bits(&bc) {
                return Err(format!("{} on {}: the body's readings differ from the reference path's", b.prefix, dev.name()));
            }
            values += rm.len() + rc.len();
        }
        win.release_device();
    }
    let _ = writeln!(
        rep,
        "(c) {} windows of the three-file tree on {}: every body's mass and raw-score rows equal the reference path's bit for bit ({values} values)",
        scan.windows.len(),
        dev.name()
    );
    nmengn::residency::get().release_windows();
    Ok(())
}
